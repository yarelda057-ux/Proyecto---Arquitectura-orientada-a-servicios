import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import mongoose from 'mongoose';
import ExcelJS from 'exceljs';
import { createApp } from '../app.js';
import User from '../models/user.js';
import Supplier from '../models/supplier.js';
import StockBatch from '../models/stockBatch.js';
import NotificationOutbox from '../models/notificationOutbox.js';
import { reconcileNotificationSchedules } from '../services/notificationOutboxWorker.js';
import { sendNotificationEvent } from '../services/notificationIntegration.js';
process.env.JWT_SECRET = randomBytes(48).toString('hex');
process.env.INTEGRATION_KEY = randomBytes(48).toString('hex');
process.env.INTEGRATION_ESB_KEY = randomBytes(48).toString('hex');
const dbName = 'wholesale_autonomy_test_' + randomBytes(8).toString('hex');
let server;
try {
  await mongoose.connect(process.env.TEST_MONGODB_URI || 'mongodb://127.0.0.1:27017', { dbName, serverSelectionTimeoutMS: 5000 });
  await Promise.all(Object.values(mongoose.models).map(model => model.init()));
  await User.create({ email: 'admin@example.test', password: 'admin test password long', role: 'admin' });
  server = createApp().listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = 'http://127.0.0.1:' + server.address().port;
  let token;
  async function request(path, method = 'GET', body, key) {
    return fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: 'Bearer ' + token } : {}), ...(key ? { 'Idempotency-Key': key } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  }
  const login = async (email, password) => {
    const response = await request('/api/v1/auth/login', 'POST', { email, password });
    assert.equal(response.status, 200); return (await response.json()).access_token;
  };
  assert.equal((await request('/health/ready')).status, 200);
  assert.equal((await request('/api/v1/stock/products')).status, 401);
  token = await login('admin@example.test', 'admin test password long');
  const admin = token;
  let response = await request('/api/v1/stock/proveedores', 'POST', { nombre: 'Mayorista prueba', correoContacto: 'supplier@example.test' });
  assert.equal(response.status, 201);
  const { proveedor } = await response.json();
  const supplierDoc = await Supplier.findOne({ supplierId: proveedor.idMayorista });
  await reconcileNotificationSchedules();
  assert.equal(await NotificationOutbox.countDocuments({ eventId: 'schedule:' + proveedor.idMayorista + ':1', eventType: 'sync-schedule' }), 1);
  let scheduleBody;
  await sendNotificationEvent({ eventId: 'baseline-registration', eventType: 'sync-schedule' }, supplierDoc, { fetchImpl: async (_url, options) => { scheduleBody = JSON.parse(options.body); return new Response('{}', { status: 200 }); } });
  assert.equal(scheduleBody.LastCatalogUpdate, supplierDoc.createdAt.toISOString(), 'proveedor nuevo usa fecha de registro');
  const supplierPath = '/api/v1/stock/proveedores/' + proveedor.idMayorista;
  response = await request(supplierPath + '/usuarios', 'POST', { email: 'supplier@example.test', password: 'supplier test password long' });
  assert.equal(response.status, 201);
  const { usuario } = await response.json();
  assert.equal((await request(supplierPath + '/usuarios', 'POST', { email: 'duplicate@example.test', password: 'supplier test password long' })).status, 409);
  token = await login(usuario.email, 'supplier test password long');
  const supplierToken = token;
  assert.equal((await request('/api/v1/stock/proveedores', 'POST', {})).status, 403);
  const book = new ExcelJS.Workbook(); const sheet = book.addWorksheet('Stock');
  sheet.addRows([[], ['PartNumber', 'Descripción', 'QTY', 'Precio US$'], ['FG-40F', 'FortiGate', 16, 420.43]]);
  response = await request('/api/v1/stock/upload', 'POST', { idMayorista: proveedor.idMayorista, formato: 'XLSX', archivoBase64: Buffer.from(await book.xlsx.writeBuffer()).toString('base64') }, 'upload-001');
  assert.equal(response.status, 202); const batch = await response.json();
  assert.equal((await request('/api/v1/stock/lotes/' + batch.idLote + '/confirmacion', 'POST', {}, 'confirm-001')).status, 200);
  const processedBatch = await StockBatch.findOne({ batchId: batch.idLote });
  const catalogEvent = await NotificationOutbox.findOne({ eventId: 'catalog:' + batch.idLote });
  assert.ok(catalogEvent); assert.equal(catalogEvent.catalogAt.toISOString(), processedBatch.processedAt.toISOString());
  assert.equal((await request('/api/v1/stock/lotes/' + batch.idLote + '/confirmacion', 'POST', {}, 'confirm-001')).status, 200);
  assert.equal(await NotificationOutbox.countDocuments({ eventId: 'catalog:' + batch.idLote }), 1, 'confirmación repetida no duplica evento');
  let uploadedScheduleBody;
  await sendNotificationEvent({ eventId: 'baseline-upload', eventType: 'sync-schedule' }, await Supplier.findOne({ supplierId: proveedor.idMayorista }), { fetchImpl: async (_url, options) => { uploadedScheduleBody = JSON.parse(options.body); return new Response('{}', { status: 200 }); } });
  assert.equal(uploadedScheduleBody.LastCatalogUpdate, processedBatch.processedAt.toISOString(), 'carga confirmada usa processedAt');
  token = admin;
  response = await request('/api/v1/stock/notificaciones/' + proveedor.idMayorista + '/mensaje', 'PUT', { mensajeAdicional: 'Aviso de prueba' });
  token = supplierToken;
  assert.equal(response.status, 200); assert.equal((await Supplier.findOne({ supplierId: proveedor.idMayorista })).additionalMessage, 'Aviso de prueba');
  await reconcileNotificationSchedules();
  assert.equal(await NotificationOutbox.countDocuments({ supplierId: proveedor.idMayorista, eventType: 'sync-schedule' }), 2, 'mensaje nuevo encola revisión idempotente');

  token = admin;
  response = await request('/api/v1/stock/notificaciones/' + proveedor.idMayorista + '/estado', 'PUT', { activa: false });
  assert.equal(response.status, 200);
  const canceledSupplier = await Supplier.findOne({ supplierId: proveedor.idMayorista });
  assert.equal(canceledSupplier.notificationsEnabled, false);
  await reconcileNotificationSchedules();
  assert.equal(await NotificationOutbox.countDocuments({ supplierId: proveedor.idMayorista, eventType: 'cancel-schedule' }), 1, 'cancelación manual encola evento');
  assert.equal((await request('/api/v1/stock/notificaciones/' + proveedor.idMayorista + '/estado', 'PUT', { activa: true })).status, 200);
  assert.equal((await Supplier.findOne({ supplierId: proveedor.idMayorista })).notificationsEnabled, true, 'reactivación de recordatorios conserva proveedor');
  token = supplierToken;
  response = await request('/api/v1/stock/products');
  assert.equal((await response.json()).productos[0].cantidad, 16);
  assert.equal((await request('/api/v1/stock/products?idMayorista=MAY-OTHER')).status, 403);
  response = await request('/api/v1/stock/historial?idMayorista=' + proveedor.idMayorista);
  assert.equal(response.status, 200);
  assert.equal((await response.json()).items[0].batchId, batch.idLote);
  response = await request('/api/v1/stock/lotes/' + batch.idLote + '/preview');
  assert.equal((await response.json()).items[0].cantidad, 16);
  response = await request('/api/v1/stock/lotes/' + batch.idLote + '/excel');
  const archived = await response.json();
  assert.equal(archived.original, true);
  const downloaded = new ExcelJS.Workbook();
  await downloaded.xlsx.load(Buffer.from(archived.archivoBase64, 'base64'));
  assert.equal(downloaded.worksheets[0].getCell('A3').value, 'FG-40F');
  assert.equal((await request('/api/v1/stock/historial?idMayorista=MAY-OTHER')).status, 403);
  response = await request('/api/v1/stock/historial?fecha=2000-01-01');
  assert.equal((await response.json()).total, 0);
  const resetPath = supplierPath + '/usuarios/' + usuario.id + '/password';
  assert.equal((await request(resetPath, 'PUT', { password: 'new supplier password long' })).status, 403);
  token = admin;
  assert.equal((await request(resetPath, 'PUT', { password: 'new supplier password long' })).status, 200);
  token = supplierToken;
  assert.equal((await request('/api/v1/auth/profile')).status, 401);
  assert.equal((await request('/api/v1/auth/login', 'POST', { email: usuario.email, password: 'supplier test password long' })).status, 401);
  token = await login(usuario.email, 'new supplier password long');
  assert.equal((await request('/api/v1/auth/logout', 'POST', {})).status, 200);
  assert.equal((await request('/api/v1/auth/profile')).status, 401);
  token = admin;
  assert.equal((await request(supplierPath, 'PUT', { activo: false })).status, 200);
  await reconcileNotificationSchedules();
  assert.equal(await NotificationOutbox.countDocuments({ supplierId: proveedor.idMayorista, eventType: 'cancel-schedule' }), 2, 'la cancelación manual y la desactivación encolan eventos');
  console.log('PASS: mayoristas, autenticación, lotes y sincronización idempotente de notificaciones.');
} finally {
  if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
  if (mongoose.connection.name === dbName) await mongoose.connection.dropDatabase();
  await mongoose.disconnect();
}
